#!/usr/bin/env python3
"""Builds the ambience SAMPLES in assets/sound/ambience/ from the sources declared below.

Like tools/make_icons.py, the files are generated, not hand-edited: every sample is a CC0 recording
from Freesound, fetched, cut, looped, normalised and written as 16-bit FLAC (gapless: a loop point
survives, unlike MP3's encoder padding). Re-run after editing SOURCES; the recordings are cached.

    tools/harness/.venv/Scripts/python tools/make_ambience.py [name ...] [--audition]

Needs numpy + soundfile (tools/harness/requirements.txt). --audition also writes 16-bit WAVs of the
results into the cache and prints the imgtools command that draws their spectrograms.

What happens to a source:
  (both)  `highpass` Hz first, if set: wind rumble and handling noise under a bird or insect bed
          cost the music its bass and carry nothing of the place.
  loop    [start, end) seconds of the recording, the last `xfade` seconds folded over the start with
          an equal-power crossfade (so the end runs straight back into the beginning), loudness-
          normalised to `lufs` (ungated BS.1770), resampled to 48 kHz if needed.
  events  the recording is split into its individual calls (envelope above `thresh` dB below the
          loudest peak, at least `min_s` long, padded and faded), the `count` loudest kept, each
          peak-normalised to `peak` dBFS: <name>_1.flac ... for an "events" layer.

Downloads use Freesound's public HQ previews (128 kbps MP3). They are the same recordings under the
same licence; for lossless originals, download them while logged in and put them in the cache as
<id>.wav — a cached WAV is preferred over the preview.

Every source's licence is re-checked on its Freesound page (CC0 only) and credited in
assets/sound/ambience/CREDITS.txt, which this script writes.
"""
