"""Data step: replay the observed passes (passes/mmt_passes.json) through the sim's photometry, and write the inputs
for the engine clips.

    out/sat_lighting/data/passes/<id>.out.json     SatModelTool --pass trace (SGP4 states, 10 Hz)
    out/sat_lighting/data/passes/replica_roster.json   the first pass's satellite as a roster entry for the app
    out/sat_lighting/data/clips/replica_pass.satcmd     the app tracking that satellite from the observatory
    out/sat_lighting/data/clips/mirror_flare.satcmd     a Reflect mirror flaring, seen from its target site
Run by `python -m vidkit data sat_lighting`.
"""
from __future__ import annotations

import json
import sys
from datetime import timedelta
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))

from vidkit import env, passes  # noqa: E402

MODELS = {"VisorSat": "starlink_visorsat", "V1.0": "starlink_v1_0"}
PAD_S = 3.0          # simulate a little before / after the observed span
FPS = 30
CLIP_SPEED = 2.0     # the replica clip plays at 2x real time


def model_for(p):
    return MODELS["V1.0"] if "V1.0" in p["version"] else MODELS["VisorSat"]


def frame_loop(t_start: float, n: int, dt: float, prefix: str = "f") -> list[str]:
    """One capture per frame at exact sim times (seconds since J2000). Time stays paused and is SET each frame: a
    capture spans several app frames, so with time running each recorded frame held 4-5x its share of sim time."""
    out = []
    for i in range(n):
        out += [f"time j2000 {t_start + i * dt:.4f}", "wait 1", f"capture {prefix}_{i:05d}"]
    return out


def main():
    data = env.out_dir("sat_lighting", "data")
    work = env.out_dir("sat_lighting", "data", "passes")
    clips = env.out_dir("sat_lighting", "data", "clips")
    obs = json.loads((HERE / "passes" / "mmt_passes.json").read_text(encoding="utf-8"))["passes"]
    for p in obs:
        a = passes.parse_utc(p["utc_start"]) - timedelta(seconds=PAD_S)
        b = passes.parse_utc(p["utc_end"]) + timedelta(seconds=PAD_S)
        model = model_for(p)
        spec = passes.pass_spec(p["tle"], p["observer"], a, b, 0.1, model=str(env.REPO / "data" / "satellite_models" /
                                                                             f"{model}.json"),
                                tle_offset_s=p.get("tle_time_offset_s", 0.0))
        out = passes.run_pass(spec, work, p["id"])
        out["observed"] = p
        (work / f"{p['id']}.out.json").write_text(json.dumps(out), encoding="utf-8")

    # The first (recommended) pass as a satellite in the app, and a script that films it.
    p = obs[0]
    t0, t1 = passes.parse_utc(p["utc_start"]), passes.parse_utc(p["utc_end"])
    mid = t0 + (t1 - t0) / 2
    member = passes.circular_member(p["tle"], mid, f"{p['satellite']} (replica)", p.get("tle_time_offset_s", 0.0))
    (work / "replica_roster.json").write_text(json.dumps(passes.extra_roster(member, "Starlink VisorSat (geometry model)"),
                                                        indent=1), encoding="utf-8")
    start = (t0 - timedelta(seconds=PAD_S)).replace(microsecond=0)
    span = (t1 - t0).total_seconds() + 2 * PAD_S
    n = int(span * FPS / CLIP_SPEED)
    o = p["observer"]
    lines = [f"# generated by make_pass.py: {p['satellite']} from {o['name']}, {p['utc_start']} (x{CLIP_SPEED:g})",
             "time pause", "ui hide",
             "set clouds_v2.coverage 0", "set clouds_v2.auto_exposure 0",
             "set photometry.sat_part_occlusion true",   # the benchmarked configuration (the visor shades the antennas)
             f"observer lat={o['lat_deg']} lon={o['lon_deg']} agl=2",
             f"time set {start.isoformat().replace('+00:00', 'Z')}",
             "camera fov=4",  # before Track: any explicit camera command releases it
             'select const "Replica pass"', "track on", "state",
             "wait settle", "wait 30"] + frame_loop(passes.t_j2000(start), n, CLIP_SPEED / FPS) + ["quit"]
    (clips / "replica_pass.satcmd").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # A flare the model does produce: Reflect mirror (roster index 1064776) easing its beam onto the Topaz site, where
    # the observer stands: aim error 7.2 deg at 01:53:15 -> 0.18 deg at 01:54:30 (found with harness `beams sats site=18`).
    lines = ["# generated by make_pass.py: a Reflect Orbital mirror lighting up, telephoto from its target site",
             "time pause", "ui hide",
             "set clouds_v2.coverage 0", "set clouds_v2.auto_exposure 0", "set clouds_v2.exposure_ev 0",
             "observer lat=35.38 lon=-120.05 agl=2",
             "time set 2036-11-22T01:54:00Z",
             "camera fov=2.5",  # before Track: any explicit camera command releases it
             "select sat 1064776", "track on", "state",
             "wait settle", "wait 30"] + frame_loop(passes.t_j2000("2036-11-22T01:54:00Z"), int(45 * FPS), 1.0 / FPS) + ["quit"]
    (clips / "mirror_flare.satcmd").write_text("\n".join(lines) + "\n", encoding="utf-8")
    # The same mirror from a point on its beam spot's path, 18 km short of Topaz: the spot sweeps over the observer at
    # about 4.7 km/s near 01:54:33.7 and settles on Topaz; no other mirror's beam lands here.
    lines = ["# generated by make_pass.py: a Reflect mirror's beam spot sweeping over an observer on its way to Topaz",
             "time pause", "ui hide",
             "set clouds_v2.coverage 0", "set clouds_v2.auto_exposure 0", "set clouds_v2.exposure_ev 0",
             "observer lat=35.50 lon=-120.012 agl=2",
             "time set 2036-11-22T01:54:20Z",
             "camera fov=2.5",
             "select sat 1064776", "track on", "state",
             "wait settle", "wait 30"] + frame_loop(passes.t_j2000("2036-11-22T01:54:20Z"), int(25 * FPS), 1.0 / FPS) + ["quit"]
    (clips / "mirror_sweep.satcmd").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("passes:", [p["id"] for p in obs], "| clips:", [f.name for f in clips.glob("*.satcmd")])


if __name__ == "__main__":
    main()
